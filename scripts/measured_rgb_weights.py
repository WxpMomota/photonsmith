#!/usr/bin/env python3
"""Writes src/shared/measured_rgb_quadrature.h: the quadrature a measured BSDF's spectral table is turned into RGB with.

pbrt-v4's MeasuredBxDF returns a spectrum (the table is evaluated at the sampled wavelengths) and the film sensor turns it into RGB. This renderer is RGB, so it used to evaluate
the table at three fixed wavelengths (612, 549, 465 nm), which reads a table's blue 16% high against pbrt (`measured-furnace`). The RGB a reflectance spectrum S(lambda) has under
white light is  RGB_c = sum_k W_c,k S(lambda_k),  W_c,k = (sRGB-from-XYZ row c) . integral over bin k of (CIE xyz bar)(lambda) D65(lambda) d lambda, normalised so S = 1 gives (1, 1, 1).
The CIE tables and the D65 illuminant are read from a pbrt-v4 source tree (src/pbrt/util/spectrum.cpp).

    python scripts/measured_rgb_weights.py --pbrt-src C:/Users/xinpe/source/repos/pbrt-v4
"""
import argparse
import os
import re

BIN = 20.0           # nm
FIRST, LAST = 360.0, 830.0
XYZ_TO_SRGB = [[3.2404542, -1.5371385, -0.4985314], [-0.9692660, 1.8760108, 0.0415560], [0.0556434, -0.2040259, 1.0572252]]


def floats(text, name):
    m = re.search(r"const Float %s\[[^\]]*\]\s*=\s*\{(.*?)\};" % name, text, re.S)
    return [float(x) for x in re.findall(r"[-+]?\d+\.?\d*(?:[eE][-+]?\d+)?", m.group(1))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pbrt-src", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "shared", "measured_rgb_quadrature.h"))
    args = ap.parse_args()
    text = open(os.path.join(args.pbrt_src, "src", "pbrt", "util", "spectrum.cpp"), encoding="utf-8", errors="replace").read()
    X, Y, Z, lam = floats(text, "CIE_X"), floats(text, "CIE_Y"), floats(text, "CIE_Z"), floats(text, "CIE_lambda")
    d65 = floats(text, "CIE_Illum_D6500")
    dl, dv = d65[0::2], d65[1::2]

    def illum(l):
        for i in range(len(dl) - 1):
            if dl[i] <= l <= dl[i + 1]:
                t = (l - dl[i]) / (dl[i + 1] - dl[i])
                return dv[i] * (1 - t) + dv[i + 1] * t
        return 0.0

    edges = []
    e = FIRST
    while e < LAST:
        edges.append((e, min(e + BIN, LAST)))
        e += BIN
    bins = []
    for lo, hi in edges:
        acc = [0.0, 0.0, 0.0]
        for i, l in enumerate(lam):
            if lo <= l < hi or (hi == LAST and l == LAST):
                w = illum(l)
                acc[0] += X[i] * w; acc[1] += Y[i] * w; acc[2] += Z[i] * w
        # the bin's centre of mass in lambda, weighted by luminance*illuminant, is where the table is evaluated
        num = den = 0.0
        for i, l in enumerate(lam):
            if lo <= l < hi or (hi == LAST and l == LAST):
                w = (Y[i] + 1e-3) * illum(l)
                num += l * w; den += w
        bins.append(((num / den) if den else (lo + hi) / 2, acc))
    rgb = [[sum(XYZ_TO_SRGB[c][j] * b[1][j] for j in range(3)) for b in bins] for c in range(3)]
    for c in range(3):   # S = 1 reads 1 in every channel
        s = sum(rgb[c])
        rgb[c] = [v / s for v in rgb[c]]
    keep = [k for k in range(len(bins)) if max(abs(rgb[c][k]) for c in range(3)) > 4e-4]
    for c in range(3):
        s = sum(rgb[c][k] for k in keep)
        for k in keep:
            rgb[c][k] /= s
    lines = []
    lines.append("// measured_rgb_quadrature.h -- GENERATED by scripts/measured_rgb_weights.py (pbrt-v4's CIE tables and D65 illuminant); do not edit.")
    lines.append("//")
    lines.append("// How a measured BSDF's spectral table becomes RGB: the table is evaluated at RT_MEASURED_LAMBDAS (nm), and RGB_c = sum_k RT_MEASURED_W{R,G,B}[k] * S(lambda_k) (clamped at 0).")
    lines.append("// A reflectance of 1 at every wavelength gives (1, 1, 1) under white (D65) light, as it does through pbrt's film sensor. The old three fixed wavelengths (612, 549, 465 nm)")
    lines.append("// read the blue of the bundled tables 16% high against pbrt. Macros so the CPU (double), both OptiX backends (__constant__ float) and Metal read the same numbers.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#define RT_MEASURED_BINS %d" % len(keep))
    for name, vals in (("RT_MEASURED_LAMBDAS", [bins[k][0] for k in keep]), ("RT_MEASURED_WR", [rgb[0][k] for k in keep]), ("RT_MEASURED_WG", [rgb[1][k] for k in keep]), ("RT_MEASURED_WB", [rgb[2][k] for k in keep])):
        lines.append("#define %s %s" % (name, ", ".join("%.6ff" % v for v in vals)))
    open(args.out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d bins -> %s" % (len(keep), args.out))
    for c, n in enumerate("RGB"):
        print(n, " ".join("%.3f" % rgb[c][k] for k in keep))
    print("lam", " ".join("%.0f" % bins[k][0] for k in keep))


main()
